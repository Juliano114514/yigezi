let LANG = 'en';
try { if (localStorage.getItem('yigezi.language') === 'zh') LANG = 'zh'; } catch (_) {}

function t(key, params = {}, lang = LANG) {
  const message = I18N[lang][key];
  if (typeof message !== 'string') throw new Error('Missing translation key: ' + key);
  return message.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? '{' + name + '}'));
}

window.YigeziI18n = { t, get language() { return LANG; } };
