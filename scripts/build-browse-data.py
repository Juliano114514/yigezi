#!/usr/bin/env python3
"""Rebuild offline catalogues from frozen data/ inputs; no network or extra packages.

Normal runs never read the neighbouring Flashcard project. --check compares
generated bytes without rewriting files. The independent character grades are
separate from the CSV word-learning stages.
"""
import argparse
import collections
import csv
import hashlib
import io
import json
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
VERSION = "2026-11-03.1"
REVISION = "6553a350763ce4feca2c5d1cc2cad7e594dc2975"
SOURCE_FILES = {"wordlist-source.csv", "legacy-inputs.json", "modern-source.json",
                "common-characters.json", "shuowen-source.json", "translation-source.json"}


def encode(value, pretty=False):
    return (json.dumps(value, ensure_ascii=False, indent=2 if pretty else None,
                       separators=None if pretty else (",", ":")) + "\n").encode("utf-8")


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def read(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def pinyin_key(value):
    """Flashcard ordering: each syllable's letters then tone; ü follows u."""
    result = []
    for part in re.split(r"[\s'’\-]+", value.strip().lower()):
        if not part:
            continue
        letters, tone = [], 5
        for char in unicodedata.normalize("NFD", part):
            if char in "\u0304\u0301\u030c\u0300":
                tone = "\u0304\u0301\u030c\u0300".index(char) + 1
            else:
                letters.append(char)
        syllable = unicodedata.normalize("NFC", "".join(letters))
        weights = tuple(ord("u") * 2 + 1 if c == "ü" else ord("e") * 2 + 1
                        if c == "ê" else ord(c) * 2 for c in syllable)
        result.append((weights, tone))
    return tuple(result)


def readings(record):
    for field in ("kTGHZ2013", "kXHC1983", "kMandarin"):
        if record.get(field):
            return list(dict.fromkeys(part.split(":")[-1] for part in record[field].split()))
    return []


def tgh(record):
    return int(record["kTGH"].split(":")[1]) if record.get("kTGH") else 999999


def vocabulary():
    with (DATA / "wordlist-source.csv").open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream))
    words = [{"id": r["词条ID"], "hanzi": r["组词"], "pinyin": r["拼音"],
              "english": r["英文释义"], "pos": r["词性"], "rarity": int(r["罕度"]),
              "source": "flashcard:" + r["词条ID"]} for r in rows]
    if len(words) != 15585 or len({w["id"] for w in words}) != len(words) or len({w["hanzi"] for w in words}) != len(words):
        raise ValueError("Frozen vocabulary must contain 15,585 unique IDs and headwords")
    if any(w["rarity"] not in (0, 1, 2) or not 1 <= len(w["hanzi"]) <= 32
           or any(not 0x4E00 <= ord(c) <= 0x9FFF for c in w["hanzi"]) for w in words):
        raise ValueError("Invalid frozen vocabulary headword or rarity")
    words.sort(key=lambda w: (w["rarity"], pinyin_key(w["pinyin"]), w["id"]))
    required = {c for w in words for c in w["hanzi"]}
    if len(required) != 3716:
        raise ValueError("Expected 3,716 required characters")
    return words, required


def grade(legacy, modern, required, allow_unreviewed):
    common = read("common-characters.json")
    first, second = set(common["common"]), set(common["lessCommon"])
    if len(first) != 2500 or len(second) != 1000 or first & second:
        raise ValueError("Invalid 2,500 + 1,000 common-character baseline")
    if not (DATA / "rarity-overrides.json").exists() and not allow_unreviewed:
        raise ValueError("Independent character-rarity review is missing")
    review = read("rarity-overrides.json") if (DATA / "rarity-overrides.json").exists() else {"overrides": {}}
    original = set(legacy["originalBrowseCharacters"])
    candidates = original | required
    baseline = first | second
    review_candidates = [c for c in candidates if c not in baseline and tgh(modern.get(c, {})) <= 6500]
    if not allow_unreviewed and review.get("reviewedCandidateCount") != len(review_candidates):
        raise ValueError("Editorial review does not cover all %d modern-commonness candidates" % len(review_candidates))
    if set(review["overrides"]) - candidates:
        raise ValueError("Editorial override outside the frozen candidate set")
    decisions, active = [], {}
    for char in sorted(candidates):
        record = modern.get(char, {})
        index = tgh(record)
        if char in first:
            value, source, reason = 0, "common-1988:2500", "1988现代汉语常用字表2500常用字。"
        elif char in second:
            value, source, reason = 1, "common-1988:1000", "1988现代汉语常用字表1000次常用字。"
        elif index <= 6500:
            value, source = 2, "unihan-18:kTGH:" + str(index)
            reason = "2013通用规范一级新增/二级字；按现代通用程度初评2，结合逐字编辑覆盖。"
        elif index <= 8105:
            value, source, reason = 3, "unihan-18:kTGH:" + str(index), "通用规范三级字，主要用于姓名地名和专门术语，初评3。"
        else:
            value, source, reason = 4, "unihan-18:no-kTGH", "现代通用规范表外古旧/异体候选，初评4；不以表外直接断言罕见。"
        base = value
        override = review["overrides"].get(char)
        if override:
            value = override["rarity"]
            if type(value) is not int or value not in range(5) or not override.get("reason"):
                raise ValueError("Invalid editorial override: " + char)
            source, reason = "editorial-review", override["reason"]
        independent = value
        adjusted = char in required and value > 2
        if adjusted:
            value = 2
            reason += " 用户确认：0–2词表必需字封顶2，保证全部词表字符支持。"
        decisions.append({"character": char, "codepoint": "U+%04X" % ord(char),
                          "wasMain": char in original, "required": char in required,
                          "baseRarity": base, "independentRarity": independent, "rarity": value,
                          "action": "retain" if value <= 2 else "remove", "source": source,
                          "reason": reason, "requiredAdjustment": adjusted,
                          "tgh": record.get("kTGH", ""), "definition": record.get("kDefinition", "")})
        if value <= 2:
            active[char] = {"p": readings(record), "r": [], "rarity": value,
                            "required": char in required, "entries": []}
    if not required <= set(active):
        raise ValueError("A required character was removed")
    return active, decisions, review


def forms(char, legacy, modern):
    result = list(dict.fromkeys(char + legacy["TS"].get(char, "")))
    for code in modern.get(char, {}).get("kTraditionalVariant", "").split():
        match = re.match(r"U\+([0-9A-F]+)", code)
        if match:
            variant = chr(int(match.group(1), 16))
            if variant not in result:
                result.append(variant)
    return result


def history(active, legacy, modern, source):
    translations = read("translation-source.json")["entries"]
    entries = {}
    for identifier, entry in source["entries"].items():
        old = translations.get(entry["head"], {})
        status, english = "unavailable", ""
        if old.get("e") == entry["e"]:
            status, english = "retained-exact", old["eEn"]
        elif old.get("e") and re.sub(r"\s+", "", old["e"]) == re.sub(r"\s+", "", entry["e"]):
            status, english = "retained-whitespace-normalized", old["eEn"]
        entries[identifier] = dict(entry, eEn=english, translationStatus=status)
    override_path = DATA / "shuowen-translation-overrides.json"
    if override_path.exists():
        overrides = read("shuowen-translation-overrides.json")
        for identifier, override in overrides.get("entries", overrides).items():
            if identifier not in entries or override["e"] != entries[identifier]["e"] or not override.get("eEn"):
                raise ValueError("Stale or invalid project English translation: " + identifier)
            entries[identifier]["eEn"] = override["eEn"]
            entries[identifier]["translationSource"] = "project-editorial"
            entries[identifier]["translationStatus"] = "project-editorial"
    radicals = source["radicals"]
    if source["revision"] != REVISION or source["entryCount"] != 9833 or len(radicals) != 540 or len({r["id"] for r in radicals}) != 540:
        raise ValueError("Expected fixed 9,833-entry source and 540 Shuowen departments")
    heads, indexes, variants = [collections.defaultdict(list) for _ in range(3)]
    for identifier, entry in entries.items():
        heads[entry["head"]].append(identifier)
        for value in entry["indexes"]:
            indexes[value].append(identifier)
        for value in entry["variants"]:
            variants[value["head"]].append(identifier)
    used, relationships = set(), {}
    history_review = read("history-overrides.json")["characters"]
    if set(history_review) - set(active):
        raise ValueError("History override outside the supported main-character set")
    for char, record in active.items():
        identifiers, evidence, scores = [], [], {}
        for form_order, form in enumerate(forms(char, legacy, modern)):
            for relation, lookup in (("head", heads), ("index", indexes), ("variant", variants)):
                for identifier in lookup.get(form, []):
                    if identifier not in identifiers:
                        identifiers.append(identifier)
                    score = ({"head": 0, "variant": 1, "index": 2}[relation], form_order)
                    scores[identifier] = min(scores.get(identifier, score), score)
                    evidence.append({"id": identifier, "form": form, "relation": relation})
        override = history_review.get(char, {})
        excluded, preferred = override.get("exclude", []), override.get("preferred", [])
        if not set(excluded + preferred) <= set(identifiers) or set(excluded) & set(preferred):
            raise ValueError("Stale or conflicting historical identity override: " + char)
        for item in evidence:
            if item["id"] in excluded:
                item.update(excluded=True, overrideReason=override["reason"])
            elif item["id"] in preferred:
                item.update(preferred=True, overrideReason=override["reason"])
        identifiers = [i for i in identifiers if i not in excluded]
        # Same-shaped historical entries retain their separate IDs. Prefer the
        # prior exact-translated sense without assigning its English elsewhere.
        positions = {identifier: index for index, identifier in enumerate(identifiers)}
        identifiers.sort(key=lambda i: (preferred.index(i) if i in preferred else len(preferred),
                                        scores[i], entries[i]["translationStatus"] != "retained-exact", positions[i]))
        record["entries"] = identifiers
        record["r"] = list(dict.fromkeys(entries[i]["rid"] for i in identifiers))
        relationships[char] = evidence
        used.update(identifiers)
        if not record["p"]:
            record["p"] = list(dict.fromkeys(entries[i]["p"] for i in identifiers if entries[i]["p"]))
        if not record["p"]:
            raise ValueError("No grounded Mandarin reading: " + char)
    # Departments remain navigable independently of the main-character filter.
    used.update(radical["id"][3:] for radical in radicals)
    return {i: entries[i] for i in sorted(used, key=int)}, radicals, relationships


def csv_data(rows, fields):
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
    writer.writeheader()
    writer.writerows(rows)
    return stream.getvalue().encode("utf-8")


def constant(name, value):
    return ("// Generated by scripts/build-browse-data.py from frozen data/ inputs.\n"
            "// Data sources and separate licences: THIRD_PARTY_NOTICES.md.\nconst " + name + " = "
            + json.dumps(value, ensure_ascii=False, indent=0, separators=(",", ":")) + ";\n").encode("utf-8")


def compatibility(active, legacy, modern):
    # Glyph conversion is independent of historical-dictionary coverage. A
    # traditional form is useful even when Shuowen has no entry for that form.
    ts = {char: "".join(forms(char, legacy, modern)[1:]) for char in active}
    values = {"TS": {c: value for c, value in ts.items() if value},
              "HAS_SEAL": legacy["HAS_SEAL"], "HAS_ORAC": legacy["HAS_ORAC"],
              "SURNAME": {c: p for c, p in legacy["SURNAME"].items() if c in active},
              "XZ": {c: n for c, n in legacy["XZ"].items() if c in active}}
    return b"// Glyph mappings and font coverage; metadata does not add supported mains.\n" + b"".join(
        ("const " + key + "=" + json.dumps(value, ensure_ascii=False, separators=(",", ":")) + ";\n").encode("utf-8")
        for key, value in values.items())


def generate(allow_unreviewed):
    manifest = read("source-manifest.json")
    if set(manifest["snapshots"]) != SOURCE_FILES:
        raise ValueError("Unexpected frozen source manifest paths")
    for name, expected in manifest["snapshots"].items():
        if digest((DATA / name).read_bytes()) != expected:
            raise ValueError("Frozen source changed without review: " + name)
    legacy, modern, source = read("legacy-inputs.json"), read("modern-source.json")["records"], read("shuowen-source.json")
    words, required = vocabulary()
    active, decisions, review = grade(legacy, modern, required, allow_unreviewed)
    retained, radicals, links = history(active, legacy, modern, source)
    characters = sorted(active, key=lambda c: (active[c]["rarity"], pinyin_key(" ".join(active[c]["p"])), ord(c)))
    active = {c: active[c] for c in characters}
    meta = {"version": VERSION, "schemaVersion": 1, "sourceManifest": "data/source-manifest.json"}
    browse = dict(meta, characters=characters, records=active, radicals=radicals)
    wordlist = dict(meta, words=words, source=manifest["wordlist"], rarityKind="word-learning-stage",
                    stages={"0": "Primary school", "1": "Middle school", "2": "High school"})
    shuowen = dict(meta, revision=REVISION, entries=retained, licence="Apache-2.0",
                   source="https://github.com/shuowenjiezi/shuowen/tree/" + REVISION,
                   englishNote="Existing translations match identical or whitespace-only-normalized source text; project additions are marked. Empty eEn means unavailable.")
    audit_fields = ["character", "codepoint", "wasMain", "required", "baseRarity", "independentRarity", "rarity",
                    "action", "source", "reason", "requiredAdjustment", "tgh", "definition"]
    summary = {"version": VERSION, "words": len(words), "wordRarity": dict(collections.Counter(w["rarity"] for w in words)),
               "requiredCharacters": len(required), "originalMainCharacters": len(legacy["originalBrowseCharacters"]),
               "ratedCharacters": len(decisions), "supportedCharacters": len(active),
               "characterRarity": dict(collections.Counter(r["rarity"] for r in active.values())),
               "removedCharacters": sum(d["action"] == "remove" for d in decisions),
               "requiredAdjustments": [d["character"] for d in decisions if d["requiredAdjustment"]],
               "addedRequiredCharacters": sorted(required - set(legacy["originalBrowseCharacters"])),
               "editorialOverrides": len(review["overrides"]), "reviewedCandidateCount": review.get("reviewedCandidateCount", 0),
               "reviewMethod": review.get("method", "unreviewed-preview"),
               "shuowenDepartments": len(radicals), "shuowenRetainedEntries": len(retained),
               "charactersWithoutShuowen": [c for c in characters if not active[c]["entries"]],
               "entriesWithoutEnglish": [i for i, e in retained.items() if not e["eEn"]],
               "examples": {c: active[c] for c in "明后发的找花屌" if c in active},
               "evidenceNote": "Table baseline and model editorial review; not a human-certified frequency census."}
    summary["charactersWithoutShuowenCount"] = len(summary["charactersWithoutShuowen"])
    summary["entriesWithoutEnglishCount"] = len(summary["entriesWithoutEnglish"])
    summary["englishTranslationStatus"] = dict(collections.Counter(e["translationStatus"] for e in retained.values()))
    summary["historyIdentityOverrides"] = read("history-overrides.json")["characters"]
    outputs = {"browse-data.js": constant("BROWSE_DATA", browse), "wordlist-data.js": constant("WORDLIST_DATA", wordlist),
               "shuowen-data.js": constant("SHUOWEN_DATA", shuowen),
               "characters.js": compatibility(active, legacy, modern),
               "data/character-rarity-review.csv": csv_data(decisions, audit_fields),
               "data/character-removals.csv": csv_data([d for d in decisions if d["action"] == "remove"], audit_fields),
               "data/history-links.json": encode({"revision": REVISION, "characters": links}),
               "data/catalog-report.json": encode(summary, pretty=True)}
    editorial_inputs = {name: digest((DATA / name).read_bytes()) for name in
                        ("rarity-overrides.json", "history-overrides.json", "shuowen-translation-overrides.json") if (DATA / name).exists()}
    outputs["data/generated-manifest.json"] = encode({"sourceInputs": manifest["snapshots"], "editorialInputs": editorial_inputs,
        "outputs": {name: {"sha256": digest(raw), "bytes": len(raw)} for name, raw in outputs.items()}}, pretty=True)
    return outputs, summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare without writing delivery files")
    parser.add_argument("--allow-unreviewed", action="store_true", help="Explicitly unreviewed local preview")
    args = parser.parse_args()
    outputs, summary = generate(args.allow_unreviewed)
    differences = []
    for name, raw in outputs.items():
        target = ROOT / name
        if args.check:
            if not target.exists() or target.read_bytes() != raw:
                differences.append(name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
    if differences:
        raise SystemExit("Generated files differ: " + ", ".join(differences))
    print(json.dumps({k: summary[k] for k in ("words", "requiredCharacters", "supportedCharacters", "removedCharacters",
        "characterRarity", "shuowenDepartments", "shuowenRetainedEntries", "reviewedCandidateCount")}, ensure_ascii=False))
    print("Offline catalogue check passed" if args.check else "Offline catalogues generated")


if __name__ == "__main__":
    main()
